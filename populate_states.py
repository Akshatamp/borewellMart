    updated_count = 0
    not_found_count = 0
    
    print("Starting to populate states for cities...")
    print(f"Total cities in database: {cities.count()}")
    
    for city in cities:
        city_name = city.name.strip()
        
        # Look for exact match first
        if city_name in city_to_state:
            city.state = city_to_state[city_name]
            city.save()
            updated_count += 1
            print(f"✓ Updated: {city_name} -> {city_to_state[city_name]}")
        else:
            # Try case-insensitive match
            found = False
            for key, value in city_to_state.items():
                if key.lower() == city_name.lower():
                    city.state = value
                    city.save()
                    updated_count += 1
                    print(f"✓ Updated (case-insensitive): {city_name} -> {value}")
                    found = True
                    break
            
            if not found:
                not_found_count += 1
                print(f"✗ Not found in mapping: {city_name}")
    
    print(f"\nSummary:")
    print(f"Total cities processed: {cities.count()}")
    print(f"Successfully updated: {updated_count}")
    print(f"Not found in mapping: {not_found_count}")
    
    # Show unique states after update
